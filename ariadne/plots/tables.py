"""LaTeX tables of the paper, built from the result files.

    python -m ariadne.plots.tables --results results --suffix _smoke --out figures      ->  figures/tables/*.tex

Every file holds one booktabs `tabular` (no float, no caption: wrap it in table / table* in the paper) and starts with a
comment that names its sources.  Numbers are means over the seeds of a cell.  With several seeds a cell reads
"mean +- h", where h is the half width of the 95% Student t interval of the mean (n >= 3 seeds) or half the range of the
two runs (n = 2); with one seed the number stands alone.  "n/a" marks a quantity that the run or the audit does not
provide.  A table whose data is missing is skipped with a printed note.

Tables (source experiments in brackets):
    tab_race.tex, tab_race_by_concurrency.tex   the race on real systems                    [A1, A3]
    tab_serializable.tex                         SERIALIZABLE on similarity reads + keyed control [A5, A8]
    tab_ssi_soundness.tex                        predicate locks and missed conflicts per access method [A6]
    tab_cost.tex, tab_cost_all.tex               main cost table per validation predicate    [C1]
    tab_llm.tex                                  real model: calls, tokens, changed decisions, answer quality [C3, C4]
    tab_ablation.tex                             ablations                                   [E1 .. E6]
    tab_safety.tex, tab_safety_all.tex           audited commits and safety-theorem violations [B1, B5b; all experiments]
    tab_portability.tex                          Algorithm AV on every store                 [F1]
    tab_opt_vs_pess.tex                          optimistic validation vs ball predicate locks [C10]
"""
import glob, json, math, os, re

from . import style as st, load as ld

PROXIES = ("dup", "tag", "link", "top3", "set")
NA = "n/a"
NOTE = "% mean over seeds; \"a +- h\": h = half width of the 95% Student t interval (n >= 3 seeds) or half the range (n = 2).\n"


# ------------------------------------------------------------------------------------------------ formatting
def esc(s):
    return str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#").replace("_", "\\_")


def tex(spec):
    """LaTeX label of a policy / protocol spec."""
    s = st.pretty(spec)
    s = esc(s)
    s = re.sub(r"\bc=(\d+(?:\.\d+)?)", r"$c{=}\1$", s)
    s = s.replace("c-adm.", "$c$-adm.\\")
    return s


def decimals(x):
    a = abs(x)
    if a == 0:
        return 0
    if a >= 100:
        return 0
    if a >= 10:
        return 1
    if a >= 1:
        return 2
    if a >= 0.1:
        return 2
    return 3


def num(x, d=None):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return NA
    if x == 0:
        return "0"
    d = decimals(x) if d is None else d
    s = "%.*f" % (d, x)
    if d and float(s) == 0.0:
        s = "%.1g" % x
    if abs(x) >= 10000:
        s = "{:,.0f}".format(x).replace(",", "\\,")
    return s


def cell(s, d=None):
    """Stats -> "mean" or "mean $\\pm$ half"."""
    if s is None or s.n == 0:
        return NA
    if s.n == 1 or s.half == 0:
        return num(s.mean, d)
    dd = decimals(s.mean) if d is None else d
    if s.mean == 0:
        dd = decimals(s.half)
    return "%s $\\pm$ %s" % (num(s.mean, dd), num(s.half, dd))


def S(R, key, **eq):
    """Stats of `key` over the rows of R that match."""
    Rm = ld.where(R, **eq) if eq else R
    return ld.stats([ld.num(ld.get(r, key)) for r in Rm])


def seeds_note(R):
    n = sorted({len(v) for v in _groups(R).values()})
    return "%% seeds per cell: %s\n" % (", ".join(str(x) for x in n) if n else "0")


def _groups(R):
    g = {}
    for r in R:
        k = tuple((a, json.dumps(b, sort_keys=True, default=str)) for a, b in r.items() if a in ld.grid_keys([r]) and a != "seed")
        g.setdefault(k, []).append(r)
    return g


class Table:
    def __init__(self, name, colspec, sources, note=True):
        self.name, self.colspec, self.lines = name, colspec, []
        self.head = "%% %s: generated by ariadne.plots.tables from %s\n" % (name, sources) + (NOTE if note else "")
        self.ncol = len(re.sub(r"\{[^}]*\}|[@|>]", "", colspec.replace("p", "l")))

    def comment(self, text):
        self.head += "%% %s\n" % text

    def top(self, *rows):
        self.lines.append("\\toprule")
        self.lines += list(rows)
        self.lines.append("\\midrule")

    def row(self, *cells):
        self.lines.append(" & ".join(str(c) for c in cells) + " \\\\")

    def group(self, title, first=False):
        if not first:
            self.lines.append("\\midrule")
        self.lines.append("\\multicolumn{%d}{l}{\\emph{%s}} \\\\" % (self.ncol, title))

    def rule(self):
        self.lines.append("\\midrule")

    def write(self, out):
        d = os.path.join(out, "tables")
        os.makedirs(d, exist_ok=True)
        if self.lines and self.lines[-1] == "\\midrule":
            self.lines.pop()
        p = os.path.join(d, self.name + ".tex")
        with open(p, "w") as f:
            f.write(self.head)
            f.write("\\begin{tabular}{%s}\n" % self.colspec)
            f.write("\n".join(self.lines) + "\n\\bottomrule\n\\end{tabular}\n")
        print("  wrote %s" % p)
        return p


def skip(name, why):
    print("  skipped %s: %s" % (name, why))
    return []


def case_tex(c):
    return esc(st.case_label(c))


# ------------------------------------------------------------------------------------------------ 1. the race
def tab_race(results, suffix, out):
    R = [r for r in ld.rows(results, "A1_race_stores", suffix=suffix) if r.get("dup_per_100_events") is not None]
    A3 = ld.rows(results, "A3_race_realtext", suffix=suffix, quiet=True)
    A3s = ld.rows(results, "A3_race_realtext", "audit_sep.jsonl", suffix, quiet=True)
    if not R and not A3:
        return skip("tab_race", "no A1 / A3 results")
    written = []
    protos = st.policy_order(sorted(set(ld.values(R, "proto")) | set(ld.values(A3, "proto"))))
    order = ["pgvector-rc", "pgvector-rr", "qdrant", "chroma", "milvus", "lancedb", "weaviate", "faiss"]
    stores = [s for s in order if ld.where(R, case=s)] + [s for s in ld.values(R, "case") if s not in order]
    concs = sorted(ld.values(R, "workload.conc"))
    T = Table("tab_race", "l" + "r" * len(protos), "A1_race_stores/summary.jsonl, A3_race_realtext/audit_serial.jsonl + audit_sep.jsonl")
    T.comment("duplicate rows per 100 facts (dup_per_100_events); streams: redundant writes per 100 tasks (redundant_per_100_tasks)")
    T.head += seeds_note(R + A3)
    T.top(" & " + " & ".join(tex(p) for p in protos) + " \\\\")
    first = True
    if R:
        cmax = (16 if 16 in concs else concs[-1]) if concs else None     # the paper's table is at 16 concurrent tasks
        T.group("Synthetic paraphrases%s: duplicate rows per 100 facts" % (", %g concurrent agents" % cmax if cmax is not None else ""), first=True)
        first = False
        for s in stores:
            eq = {"case": s}
            if cmax is not None:
                eq["workload.conc"] = cmax
            T.row(esc(st.store_label(s)), *[cell(S(ld.where(R, **eq), "dup_per_100_events", proto=p)) for p in protos])
    clusters = [c for c in ld.values(A3, "case") if any(r.get("dup_per_100_events") is not None for r in ld.where(A3, case=c))]
    streams = [c for c in st.case_order(ld.values(A3s, "case")) if c not in clusters]
    if clusters:
        # real paraphrases of one question can be farther apart than tau, so a serial execution also stores several per
        # cluster: the race is the excess over the serial execution of the same tasks (audit_serial)
        A3x = ld.rows(results, "A3_race_realtext", "audit_serial.jsonl", suffix, quiet=True)
        T.group("Real duplicate clusters: rows in excess of the serial execution per 100 facts", first=first); first = False
        for c in clusters:
            m = re.search(r"tau(\d+(?:\.\d+)?)", c)
            lab = st.dataset_style(c)["label"] + (" ($\\tau{=}%g$)" % float(m.group(1)) if m else "")
            T.row(lab, *[cell(S(A3x, "excess_stored_per_100_events", case=c, proto=p)) for p in protos])
    if streams:
        T.group("Real streams in natural order: redundant writes per 100 tasks", first=first); first = False
        for c in streams:
            T.row(esc(st.dataset_label(c)), *[cell(S(A3s, "redundant_per_100_tasks", case=c, proto=p)) for p in protos])
    written.append(T.write(out))
    if R and len(concs) > 1:
        T = Table("tab_race_by_concurrency", "l" + "r" * (len(protos) * len(concs)), "A1_race_stores/summary.jsonl")
        T.comment("duplicate rows per 100 facts, by number of concurrent agents")
        T.head += seeds_note(R)
        T.top(" & " + " & ".join("\\multicolumn{%d}{c}{%g agents}" % (len(protos), c) for c in concs) + " \\\\",
              " ".join("\\cmidrule(lr){%d-%d}" % (2 + i * len(protos), 1 + (i + 1) * len(protos)) for i in range(len(concs))),
              "store & " + " & ".join(tex(p) for _ in concs for p in protos) + " \\\\")
        for s in stores:
            T.row(esc(st.store_label(s)), *[cell(S(R, "dup_per_100_events", case=s, proto=p, **{"workload.conc": c})) for c in concs for p in protos])
        written.append(T.write(out))
    return written


# ------------------------------------------------------------------------------------------------ 2. SERIALIZABLE
def tab_serializable(results, suffix, out):
    R = ld.rows(results, "A5_ssi_cost", suffix=suffix)
    K = ld.rows(results, "A8_keyed_control", "keyed.jsonl", suffix, quiet=True)
    if not R and not K:
        return skip("tab_serializable", "no A5 / A8 results")
    order = ["rc", "ssi", "ssi-backoff", "ssi-short", "lock-long", "lock-short", "av-exact", "av-cadm1.1"]
    protos = [p for p in order if ld.where(R, proto=p)] + [p for p in ld.values(R, "proto") if p not in order]
    cols = [("aborts_per_task", "aborts / task"), ("llm_calls_per_task", "model calls / task"), ("lat_p50_s", "p50 (s)"), ("lat_p99_s", "p99 (s)"),
            ("tps", "tasks / s"), ("dup_per_100_events", "dup. / 100 facts"), ("gave_up", "gave up")]
    T = Table("tab_serializable", "l" + "r" * len(cols), "A5_ssi_cost/summary.jsonl, A8_keyed_control/keyed.jsonl")
    T.comment("the engine caps retries of a SERIALIZABLE transaction at max_aborts (default 200); 'gave up' counts tasks that hit it")
    T.head += seeds_note(R)
    T.top("protocol & " + " & ".join(c[1] for c in cols) + " \\\\")
    first = True
    cases = [c for c in ld.values(R, "case") if str(c).startswith("fan")] + st.case_order([c for c in ld.values(R, "case") if not str(c).startswith("fan")])
    for c in cases:
        n = ld.number_in(c)
        title = "Fan-out workload, %g concurrent agents" % n if str(c).startswith("fan") and n == n else st.dataset_label(c)
        T.group(esc(title) + " (pgvector, HNSW)", first=first); first = False
        for p in protos:
            Rp = ld.where(R, case=c, proto=p)
            if Rp:
                T.row(tex(p), *[cell(S(Rp, k)) for k, _ in cols])
    if K:
        T.group("Control: the same check-then-insert on a scalar key (B-tree)", first=first)
        groups = {}                                           # (isolation, table) -> {seed: line}; a seed run again: the last line wins
        for r in K:
            groups.setdefault((r.get("iso"), r.get("table")), {})[ld.get(r, "params.seed")] = r
        for (iso, _), by_seed in groups.items():
            Rk = list(by_seed.values())
            rows_k = ld.num(Rk[0].get("table_rows"))
            lab = "%s, %s rows%s" % (esc(str(iso or "").title().replace("Read Committed", "READ COMMITTED").replace("Serializable", "SERIALIZABLE")),
                                     num(round(rows_k / 1000) * 1000) if rows_k == rows_k else NA, " (%d seeds)" % len(Rk) if len(Rk) > 1 else "")
            T.row(lab, *[cell(S(Rk, k)) if k in ("aborts_per_task", "dup_per_100_events", "gave_up") else NA for k, _ in cols])
    return [T.write(out)]


def tab_ssi_soundness(results, suffix, out):
    exp = "A6_ssi_soundness"
    locks = ld.rows(results, exp, "locks.jsonl", suffix, quiet=True)
    hole = ld.rows(results, exp, "hole.jsonl", suffix, quiet=True) + ld.rows(results, exp, "hole_ivfflat.jsonl", suffix, quiet=True)
    generic = ld.rows(results, exp, "generic.jsonl", suffix, quiet=True)
    anti = [r for r in ld.rows(results, exp, "antipodal.jsonl", suffix, quiet=True) if r.get("test") == "antipodal"]
    hammers = []
    for fn, lab in (("hammer.jsonl", "HNSW"), ("hammer_grid.jsonl", "HNSW"), ("hammer_advisory.jsonl", "HNSW + advisory lock (control)"),
                    ("hammer_seqscan.jsonl", "no index, sequential scan (control)"), ("hammer_ivfflat.jsonl", "IVFFlat, one probe (includes recall misses)")):
        for r in ld.rows(results, exp, fn, suffix, quiet=True):
            if "events_with_rows" in r:
                hammers.append((lab, r))
    # the scripts append: when a configuration was run again the last line wins (as in paper/resmap/g_pg.py)
    lastby = lambda rows, key: list({key(r): r for r in rows}.values())
    locks = lastby(locks, lambda r: r.get("index")); generic = lastby(generic, lambda r: r.get("am"))
    hole = lastby(hole, lambda r: (r.get("index"), r.get("scenario"), r.get("trial")))
    for r in ld.rows(results, exp, "patched_library.jsonl", suffix, quiet=True):
        if r.get("test", "hammer") == "hammer" and "events_with_rows" in r:
            hammers.append(("HNSW, patched library (control)", r))
    hammers = lastby(hammers, lambda x: (x[0], x[1].get("mode"), x[1].get("index"), x[1].get("m"), x[1].get("ef_construction")))
    anti = lastby(anti, lambda r: r.get("index"))
    if not (locks or hole or generic or hammers or anti):
        return skip("tab_ssi_soundness", "no A6 results")
    T = Table("tab_ssi_soundness", "llrr", "A6_ssi_soundness/{locks,hole,generic,hammer*}.jsonl", note=False)
    ver = next((r.get("versions") for r in locks + hole + generic if r.get("versions")), None)
    if ver:
        T.comment("observed on PostgreSQL %s, pgvector %s" % (ver.get("postgresql"), ver.get("pgvector")))
    T.top("access method & SIREAD locks of one read & both commit & trials \\\\")
    first = True
    if locks:
        T.group("Predicate locks taken by a SERIALIZABLE index read (pg\\_locks)", first=True); first = False
        for r in locks:
            sl = r.get("siread_locks") or {}
            T.row(esc(r.get("index")), esc(", ".join("%s: %s" % (k, v) for k, v in sorted(sl.items())) or "none") +
                  (" (ampredlocks)" if r.get("ampredlocks") else ""), "", "")
    summ = [r for r in hole if r.get("scenario") == "SUMMARY"]
    if summ:
        T.group("Deterministic reproduction (writer paused between its conflict check and the insertion)", first=first); first = False
        for r in summ:
            T.row(esc(r.get("index")) + ", window", "", r.get("hole_both_committed"), r.get("hole_trials"))
            T.row(esc(r.get("index")) + ", control (reader starts after the insertion)", "", r.get("control_both_committed"), r.get("control_trials"))
    if generic:
        T.group("The same pause in other access methods", first=first); first = False
        for r in generic:
            sr = sorted({str(x).split(":")[0] for d in (r.get("detail") or []) for x in d.get("siread", [])})
            hit = sum(1 for d in (r.get("detail") or []) if d.get("paused"))
            if (r.get("detail") or []) and hit == 0:              # the breakpoint was never reached: no evidence either way
                T.row(esc(r.get("am")), esc(", ".join(sr)), "breakpoint not reached", r.get("trials"))
            else:
                T.row(esc(r.get("am")), esc(", ".join(sr)), r.get("both_committed"), r.get("trials"))
    if anti:
        T.group("Two reads with almost antipodal queries, then two inserts (both commit / one aborts)", first=first); first = False
        for r in anti:
            T.row(esc(r.get("index")), esc(", ".join(r.get("siread_t1") or [])), "%s / %s" % (r.get("both_committed"), r.get("one_aborted")), r.get("trials"))
    if hammers:
        T.group("Without a debugger: facts stored twice / facts (Wilson 95\\% interval)", first=first); first = False
        for lab, r in hammers:
            k, n = int(r.get("events_with_duplicate", 0)), int(r.get("events_with_rows", 0))
            p, lo, hi = ld.wilson(k, n)
            cfg = "$m{=}%s$, ef\\_construction ${=}%s$" % (r.get("m"), r.get("ef_construction")) if r.get("index") == "hnsw" else ""
            T.row(esc(lab) + (", " + cfg if cfg else ""), "insertion %s ms" % num(ld.num(r.get("insert_ms_mean"))),
                  "%d (%.1f\\%%, %.1f to %.1f)" % (k, 100 * p, 100 * lo, 100 * hi), n)
    return [T.write(out)]


# ------------------------------------------------------------------------------------------------ 3. main cost table
def _cost_rows(T, R, pols):
    for p in pols:
        Rp = ld.where(R, **{"protocol.policy": p})
        if not Rp:
            continue
        T.row(tex(p), cell(S(Rp, "extra_calls_per_100")), cell(S(Rp, "dup_written_per_100")),
              *[cell(S(Rp, "div_committed_vs_exact_%." + x)) for x in PROXIES], cell(S(Rp, "rho_committed.p99"), 3),
              cell(S(Rp, "lat_p99_s")))


def tab_cost(results, suffix, out):
    exp = "C1_calls_vs_policy"
    R = ld.join(ld.rows(results, exp, suffix=suffix), ld.rows(results, exp, "audit_run.jsonl", suffix, quiet=True))
    R = [r for r in R if r.get("protocol.policy") is not None]
    if not R:
        return skip("tab_cost", "no C1 results")
    pols = st.policy_order(ld.values(R, "protocol.policy"))
    cases = st.case_order(ld.values(R, "case"))
    primary = [c for c in ("L4", "A64") if c in cases] or cases[:2]
    written = []
    for name, cs in (("tab_cost", primary), ("tab_cost_all", cases)):
        if name == "tab_cost_all" and set(cs) == set(primary):
            continue
        T = Table(name, "lrr" + "r" * len(PROXIES) + "rr", "C1_calls_vs_policy/summary.jsonl + audit_run.jsonl")
        T.comment("extra calls: model calls per 100 tasks beyond one per task; dup.: duplicate writes per 100 tasks against exact k-NN;")
        T.comment("decision differs: share of committed decisions that differ from the decision on the exact answer, per decision proxy;")
        T.comment("rho p99: 99th percentile of the approximation ratio of the committed answer at its commit position")
        T.head += seeds_note(R)
        T.top(" & extra calls & dup.\\ writes & \\multicolumn{%d}{c}{decision differs from exact (\\%%)} & $\\rho$ & latency \\\\" % len(PROXIES),
              "\\cmidrule(lr){4-%d}" % (3 + len(PROXIES)),
              "predicate & / 100 tasks & / 100 tasks & " + " & ".join({"top3": "top-3"}.get(x, x) for x in PROXIES) + " & p99 & p99 (s) \\\\")
        for i, c in enumerate(cs):
            T.group(esc(st.dataset_label(c)), first=(i == 0))
            _cost_rows(T, ld.where(R, case=c), pols)
        written.append(T.write(out))
    return written


# ------------------------------------------------------------------------------------------------ 4. real model
def _pooled_diff(details, runs_, cells, ref_cells, idx):
    """Paired difference per (seed, question) of cells against the reference cells of the same seed, pooled; (mean,
    lo, hi) with a 95 % bootstrap interval over the pairs; None without per-question details."""
    import numpy as np
    seed = lambda c: c.rsplit("_s", 1)[-1]
    ref = {seed(c): c for c in ref_cells}
    d = []
    for c in cells:
        r = ref.get(seed(c))
        a, b = details.get(runs_.get(c, {}).get("run")), details.get(runs_.get(r, {}).get("run")) if r else None
        if not a or not b:
            return None
        d += [v[idx] - b[q][idx] for q, v in a.items() if q in b and v[idx] is not None and b[q][idx] is not None]
    if not d:
        return None
    d = np.asarray(d, float); g = np.random.default_rng(0)
    m = d[g.integers(0, len(d), size=(2000, len(d)))].mean(1)
    lo, hi = np.percentile(m, [2.5, 97.5])
    return float(d.mean()), float(lo), float(hi)


