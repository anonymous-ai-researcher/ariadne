def tab_portability(results, suffix, out):
    exp = "F1_stores"
    R = ld.join(ld.rows(results, exp, suffix=suffix), ld.rows(results, exp, "audit_run.jsonl", suffix, quiet=True))
    if not R:
        return skip("tab_portability", "no F1 results")
    order = ["pgvector-hnsw", "pgvector-ivfflat", "qdrant", "chroma", "milvus", "lancedb", "weaviate", "faiss-hnsw", "faiss-ivf", "faiss-flat"]
    stores = [s for s in order if ld.where(R, case=s)] + [s for s in ld.values(R, "case") if s not in order]
    protos = st.policy_order(ld.values(R, "proto"))
    val = [p for p in protos if st.family(p) != "none"]
    ref = next((p for p in val if st.family(p) == "cadm"), val[0] if val else None)
    T = Table("tab_portability", "l" + "r" * (len(val) + len(protos) + 4), "F1_stores/summary.jsonl + audit_run.jsonl")
    T.comment("critical section and recall of the index (validation reads against exact k-NN): runs of %s" % st.pretty(ref))
    T.head += seeds_note(R)
    T.top(" & \\multicolumn{%d}{c}{extra calls / 100 tasks} & \\multicolumn{%d}{c}{dup.\\ writes / 100 tasks} & safety & commits & crit.\\ sect. & recall of \\\\" % (len(val), len(protos)),
          "\\cmidrule(lr){2-%d} \\cmidrule(lr){%d-%d}" % (1 + len(val), 2 + len(val), 1 + len(val) + len(protos)),
          "store & " + " & ".join(tex(p) for p in val) + " & " + " & ".join(tex(p) for p in protos) + " & violations & checked & (ms) & the index \\\\")
    for s in stores:
        Rs = ld.where(R, case=s)
        chk = sum(int(ld.num(ld.get(r, "safety_theorem.checked"), 0)) for r in Rs); bad = sum(int(ld.num(ld.get(r, "safety_theorem.violations"), 0)) for r in Rs)
        T.row(esc(st.store_label(s)), *[cell(S(Rs, "extra_calls_per_100", proto=p)) for p in val],
              *[cell(S(Rs, "dup_written_per_100", proto=p)) for p in protos], bad if chk else NA, num(chk) if chk else NA,
              cell(S(ld.where(Rs, proto=ref) or Rs, "cs_mean_ms")), cell(S(ld.where(Rs, proto=ref) or Rs, "recall_fresh"), 3))
    return [T.write(out)]


# ------------------------------------------------------------------------------------------------ 8. optimistic vs pessimistic
def tab_opt_vs_pess(results, suffix, out):
    exp = "C10_vs_pessimistic"
    R = ld.rows(results, exp, suffix=suffix)
    if not R:
        return skip("tab_opt_vs_pess", "no C10 results")
    per100 = lambda k: (lambda r: 100.0 * ld.num(ld.get(r, k), float("nan")) / max(ld.num(r.get("tasks"), 1), 1) if ld.get(r, k) is not None else None)
    cols = [("extra_calls_per_100", "extra calls / 100"), ("lock_wait_mean_ms", "lock wait (ms)"), (per100("ball.waits"), "waits / 100"),
            (per100("ball.deadlocks"), "deadlocks / 100"), (per100("ball.stale_reads"), "stale reads / 100"), ("lat_p99_s", "p99 (s)"), ("tps", "tasks / s")]
    T = Table("tab_opt_vs_pess", "l" + "r" * len(cols), "C10_vs_pessimistic/summary.jsonl")
    T.comment("validation = Algorithm AV with exact validation reads at tolerance c; ball lock = predicate locks on the read ball at tolerance c (client library, one process);")
    T.comment("waits, deadlocks, stale reads: counters of the ball-lock manager per 100 tasks (a deadlock victim re-reads and thinks again)")
    T.head += seeds_note(R)
    T.top("protocol & " + " & ".join(c[1] for c in cols) + " \\\\")
    protos = st.policy_order(ld.values(R, "proto"))
    lab = lambda p: ("validation, $c{=}%g$" % st.spec_c(p)) if st.family(p) in ("cadm", "cert") else ("ball lock, $c{=}%g$" % st.spec_c(p)) if st.family(p) == "ball" else tex(p)
    for i, c in enumerate(st.case_order(ld.values(R, "case"))):
        T.group(esc(st.dataset_label(c)), first=(i == 0))
        for p in protos:
            Rp = ld.where(R, case=c, proto=p)
            if Rp:
                T.row(lab(p), *[cell(S(Rp, k)) for k, _ in cols])
    return [T.write(out)]


